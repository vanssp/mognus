def _check() -> None:
    rows = MAIN + SPARES
    wikis = [r[1] for r in rows] + [r[3] for r in rows]
    rus = [r[0] for r in rows] + [r[2] for r in rows]
    dup_w = sorted({w for w in wikis if wikis.count(w) > 1})
    dup_r = sorted({w for w in rus if rus.count(w) > 1})
    if dup_w or dup_r or len(MAIN) != 200:
        raise SystemExit(
            f"pairs invalid: main={len(MAIN)} spares={len(SPARES)} "
            f"dup_wiki={dup_w} dup_ru={dup_r}"
        )


if __name__ == "__main__":
    _check()
    print(f"main={len(MAIN)} spares={len(SPARES)} creatures={(len(MAIN)+len(SPARES))*2}")
